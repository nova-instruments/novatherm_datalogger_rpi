/**
 * @brief Exibe informações do datalogger no display
 */
void oled_display_datalogger_info(oled_context_t* ctx, const char* device_name,
                                   const modbus_data_t* data, uint32_t record_count) {
    if (!ctx || !data) return;

    oled_clear(ctx);

    // Linha 1: Nome do dispositivo
    char line[32];
    snprintf(line, sizeof(line), "%s", device_name ? device_name : "N/A");
    oled_draw_string(ctx, 0, 0, line);

    // Hora atual (sem segundos) - alinhada à direita
    time_t now = time(NULL);
    struct tm* tm_info = localtime(&now);
    snprintf(line, sizeof(line), "%02d:%02d",
             tm_info->tm_hour, tm_info->tm_min);
    // Posição X = 128 - (5 caracteres * 8 pixels) = 88 pixels
    oled_draw_string(ctx, 88, 0, line);

    // Linha separadora
    oled_draw_hline(ctx, 0, 10, OLED_WIDTH);

    // Exibir temperaturas dos 7 canais (2 colunas)
    // Coluna esquerda: CH1, CH2, CH3, CH4
    // Coluna direita: CH5, CH6, CH7
    int y_pos = 16;

    for (int i = 0; i < 4; i++) {
        if (data->ch_valid[i]) {
            if (data->ch_error[i]) {
                snprintf(line, sizeof(line), "CH%d:ERR", i + 1);
            } else {
                snprintf(line, sizeof(line), "CH%d:%.1f", i + 1, data->ch_temp[i]);
            }
        } else {
            snprintf(line, sizeof(line), "CH%d:---", i + 1);
        }
        oled_draw_string(ctx, 0, y_pos, line);
        y_pos += 12;
    }

    // Coluna direita: CH5, CH6, CH7
    y_pos = 16;
    for (int i = 4; i < MODBUS_NUM_CHANNELS; i++) {
        if (data->ch_valid[i]) {
            if (data->ch_error[i]) {
                snprintf(line, sizeof(line), "CH%d:ERR", i + 1);
            } else {
                snprintf(line, sizeof(line), "CH%d:%.1f", i + 1, data->ch_temp[i]);
            }
        } else {
            snprintf(line, sizeof(line), "CH%d:---", i + 1);
        }
        oled_draw_string(ctx, 64, y_pos, line);
        y_pos += 12;
    }

    oled_display(ctx);
}

